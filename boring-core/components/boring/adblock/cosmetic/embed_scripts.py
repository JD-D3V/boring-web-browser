#!/usr/bin/env python3
"""Embed the cosmetic filter scripts in a C++ header at build time.

Usage: embed_scripts.py <output.h> <procedural_filters.js> <cosmetic_filters.js>
       embed_scripts.py --picker <output.h> <element_picker.js>

Writes kCosmeticIsolatedScript: both files wrapped in one function
expression, which CosmeticFilterAgent evaluates in its isolated world and
then calls with the native callback and the page's config. Keeping the
scripts as plain .js files lets node test them as they ship.

With --picker, writes kElementPickerScript the same way from the element
picker, for ElementPickerAgent.
"""

import sys

DELIMITER = "BORINGJS"

HEADER = """\
// Generated by components/boring/adblock/cosmetic/embed_scripts.py.
// Do not edit.

#ifndef COMPONENTS_BORING_ADBLOCK_COSMETIC_COSMETIC_SCRIPTS_H_
#define COMPONENTS_BORING_ADBLOCK_COSMETIC_COSMETIC_SCRIPTS_H_

namespace boring {{

// (sendClassIds, configJson) => undefined
inline constexpr char kCosmeticIsolatedScript[] = R"{delimiter}(
{script}){delimiter}";

}}  // namespace boring

#endif  // COMPONENTS_BORING_ADBLOCK_COSMETIC_COSMETIC_SCRIPTS_H_
"""

WRAPPER = """\
(function(sendClassIds, configJson) {{
'use strict';
{procedural}
{cosmetic}
startCosmeticFilters(sendClassIds, JSON.parse(configJson), document, window);
}})
"""


PICKER_HEADER = """// Generated by components/boring/adblock/cosmetic/embed_scripts.py.
// Do not edit.

#ifndef COMPONENTS_BORING_ADBLOCK_COSMETIC_ELEMENT_PICKER_SCRIPT_H_
#define COMPONENTS_BORING_ADBLOCK_COSMETIC_ELEMENT_PICKER_SCRIPT_H_

namespace boring {{

// (done) => undefined
inline constexpr char kElementPickerScript[] = R"{delimiter}(
{script}){delimiter}";

}}  // namespace boring

#endif  // COMPONENTS_BORING_ADBLOCK_COSMETIC_ELEMENT_PICKER_SCRIPT_H_
"""

PICKER_WRAPPER = """(function(done) {{
'use strict';
{picker}
startElementPicker(done, document, window);
}})
"""


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(output: str, header: str, script: str) -> None:
    if ")" + DELIMITER + '"' in script:
        sys.exit("script contains the raw string delimiter " + DELIMITER)
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(header.format(delimiter=DELIMITER, script=script))


def main() -> None:
    if len(sys.argv) == 4 and sys.argv[1] == "--picker":
        output, picker = sys.argv[2:]
        write(output, PICKER_HEADER, PICKER_WRAPPER.format(picker=read(picker)))
        return
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    output, procedural, cosmetic = sys.argv[1:]
    write(
        output,
        HEADER,
        WRAPPER.format(procedural=read(procedural), cosmetic=read(cosmetic)),
    )


if __name__ == "__main__":
    main()

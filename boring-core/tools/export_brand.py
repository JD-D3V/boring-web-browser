# TrueType reading (cmap format 4, head, hhea/hmtx, loca, glyf).


class Font:
    def __init__(self, data):
        self.data = data
        count = struct.unpack(">H", data[4:6])[0]
        self.tables = {}
        for i in range(count):
            tag, _sum, off, length = struct.unpack(
                ">4sIII", data[12 + 16 * i : 28 + 16 * i]
            )
            self.tables[tag.decode("latin-1")] = (off, length)
        head = self.tables["head"][0]
        self.units_per_em = struct.unpack(">H", data[head + 18 : head + 20])[0]
        self.loca_format = struct.unpack(">h", data[head + 50 : head + 52])[0]
        maxp = self.tables["maxp"][0]
        self.num_glyphs = struct.unpack(">H", data[maxp + 4 : maxp + 6])[0]
        hhea = self.tables["hhea"][0]
        self.num_hmetrics = struct.unpack(">H", data[hhea + 34 : hhea + 36])[0]

    def glyph_index(self, ch):
        data = self.data
        cmap = self.tables["cmap"][0]
        count = struct.unpack(">H", data[cmap + 2 : cmap + 4])[0]
        sub = None
        for i in range(count):
            pid, eid, off = struct.unpack(
                ">HHI", data[cmap + 4 + 8 * i : cmap + 12 + 8 * i]
            )
            fmt = struct.unpack(">H", data[cmap + off : cmap + off + 2])[0]
            if fmt == 4 and (pid, eid) in ((3, 1), (0, 3), (0, 4), (3, 0)):
                sub = cmap + off
                if (pid, eid) == (3, 1):
                    break
        if sub is None:
            raise SystemExit("font has no cmap format 4 subtable")
        code = ord(ch)
        seg2 = struct.unpack(">H", data[sub + 6 : sub + 8])[0]
        ends = sub + 14
        starts = ends + seg2 + 2
        deltas = starts + seg2
        ranges = deltas + seg2
        for i in range(seg2 // 2):
            end = struct.unpack(">H", data[ends + 2 * i : ends + 2 * i + 2])[0]
            if code > end:
                continue
            start = struct.unpack(">H", data[starts + 2 * i : starts + 2 * i + 2])[0]
            if code < start:
                return 0
            delta = struct.unpack(">h", data[deltas + 2 * i : deltas + 2 * i + 2])[0]
            roff_at = ranges + 2 * i
            roff = struct.unpack(">H", data[roff_at : roff_at + 2])[0]
            if roff == 0:
                return (code + delta) & 0xFFFF
            at = roff_at + roff + 2 * (code - start)
            gid = struct.unpack(">H", data[at : at + 2])[0]
            return (gid + delta) & 0xFFFF if gid else 0
        return 0

    def advance(self, gid):
        hmtx = self.tables["hmtx"][0]
        i = min(gid, self.num_hmetrics - 1)
        return struct.unpack(">H", self.data[hmtx + 4 * i : hmtx + 4 * i + 2])[0]

    def _glyph_range(self, gid):
        loca = self.tables["loca"][0]
        if self.loca_format == 0:
            a, b = struct.unpack(">HH", self.data[loca + 2 * gid : loca + 2 * gid + 4])
            return a * 2, b * 2
        return struct.unpack(">II", self.data[loca + 4 * gid : loca + 4 * gid + 8])

    def contours(self, gid, depth=0):
        """Contours as lists of (x, y, on_curve) in font units."""
        if depth > 8:
            raise SystemExit("composite glyph nesting too deep")
        start, end = self._glyph_range(gid)
        if start == end:
            return []
        data = self.data
        g = self.tables["glyf"][0] + start
        ncont = struct.unpack(">h", data[g : g + 2])[0]
        if ncont >= 0:
            return self._simple(g, ncont)
        return self._composite(g, depth)

    def _simple(self, g, ncont):
        data = self.data
        p = g + 10
        end_pts = list(struct.unpack(">%dH" % ncont, data[p : p + 2 * ncont]))
        p += 2 * ncont
        npts = end_pts[-1] + 1 if end_pts else 0
        ilen = struct.unpack(">H", data[p : p + 2])[0]
        p += 2 + ilen
        flags = []
        while len(flags) < npts:
            f = data[p]
            p += 1
            flags.append(f)
            if f & 8:
                rep = data[p]
                p += 1
                flags.extend([f] * rep)
        xs = []
        v = 0
        for f in flags:
            if f & 2:
                d = data[p]
                p += 1
                v += d if f & 16 else -d
            elif not f & 16:
                v += struct.unpack(">h", data[p : p + 2])[0]
                p += 2
            xs.append(v)
        ys = []
        v = 0
        for f in flags:
            if f & 4:
                d = data[p]
                p += 1
                v += d if f & 32 else -d
            elif not f & 32:
                v += struct.unpack(">h", data[p : p + 2])[0]
                p += 2
            ys.append(v)
        out = []
        first = 0
        for last in end_pts:
            out.append(
                [(xs[i], ys[i], bool(flags[i] & 1)) for i in range(first, last + 1)]
            )
            first = last + 1
        return out

    def _composite(self, g, depth):
        data = self.data
        p = g + 10
        out = []
        while True:
            flags, gid = struct.unpack(">HH", data[p : p + 4])
            p += 4
            if flags & 1:
                a1, a2 = struct.unpack(">hh", data[p : p + 4])
                p += 4
            else:
                a1, a2 = struct.unpack(">bb", data[p : p + 2])
                p += 2
            m = [1.0, 0.0, 0.0, 1.0]
            if flags & 8:
                s = struct.unpack(">h", data[p : p + 2])[0] / 16384.0
                p += 2
                m = [s, 0.0, 0.0, s]
            elif flags & 0x40:
                sx, sy = struct.unpack(">hh", data[p : p + 4])
                p += 4
                m = [sx / 16384.0, 0.0, 0.0, sy / 16384.0]
            elif flags & 0x80:
                vals = struct.unpack(">hhhh", data[p : p + 8])
                p += 8
                m = [v / 16384.0 for v in vals]
            if not flags & 2:
                raise SystemExit("point-matched composite glyphs not supported")
            for c in self.contours(gid, depth + 1):
                out.append(
                    [
                        (
                            m[0] * x + m[2] * y + a1,
                            m[1] * x + m[3] * y + a2,
                            on,
                        )
                        for x, y, on in c
                    ]
                )
            if not flags & 0x20:
                break
        return out


def fmt(v):
    s = "%.3f" % v
    s = s.rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def glyph_outline(font):
    """The B as closed contours of ('L', p) / ('Q', c, p) in the 64 box.

    Coordinates are rounded to 3 decimals once, here, so the SVG path and
    the rasteriser use exactly the same numbers.
    """
    gid = font.glyph_index(CHAR)
    if not gid:
        raise SystemExit("font has no glyph for %r" % CHAR)
    adv = font.advance(gid)
    scale = FONT_SIZE / font.units_per_em
    x0 = ANCHOR_X - adv * scale / 2.0  # text-anchor: middle

    def xf(x, y):
        return (
            float(fmt(x0 + x * scale)),
            float(fmt(BASELINE_Y - y * scale)),
        )

    contours = []
    for raw in font.contours(gid):
        pts = [(x, y, on) for x, y, on in raw]
        if not any(on for _x, _y, on in pts):
            mx = (pts[-1][0] + pts[0][0]) / 2.0
            my = (pts[-1][1] + pts[0][1]) / 2.0
            pts = [(mx, my, True)] + pts
        else:
            k = next(i for i, p in enumerate(pts) if p[2])
            pts = pts[k:] + pts[:k]
        start = pts[0]
        segs = []
        ctrl = None
        for x, y, on in pts[1:] + [start]:
            if on:
                if ctrl is None:
                    segs.append(("L", xf(x, y)))
                else:
                    segs.append(("Q", xf(*ctrl), xf(x, y)))
                    ctrl = None
            else:
                if ctrl is not None:
                    mid = ((ctrl[0] + x) / 2.0, (ctrl[1] + y) / 2.0)
                    segs.append(("Q", xf(*ctrl), xf(*mid)))
                ctrl = (x, y)
        s = xf(start[0], start[1])
        if segs and segs[-1][0] == "L" and segs[-1][1] == s:
            segs.pop()
        contours.append((s, segs))
    info = {
        "glyph_id": gid,
        "advance_units": adv,
        "units_per_em": font.units_per_em,
        "text_start_x": round(x0, 6),
    }
    return contours, info


def outline_path(contours):
    parts = []
    for start, segs in contours:
        cmd = ["M%s %s" % (fmt(start[0]), fmt(start[1]))]
        for seg in segs:
            if seg[0] == "L":
                cmd.append("L%s %s" % (fmt(seg[1][0]), fmt(seg[1][1])))
            else:
                cmd.append(
                    "Q%s %s %s %s"
                    % (fmt(seg[1][0]), fmt(seg[1][1]), fmt(seg[2][0]), fmt(seg[2][1]))
                )
        cmd.append("Z")
        parts.append("".join(cmd))
    return "".join(parts)


def outline_bounds(contours):
    xs = []
    ys = []
    for start, segs in contours:
        xs.append(start[0])
        ys.append(start[1])
        for seg in segs:
            for p in seg[1:]:
                xs.append(p[0])
                ys.append(p[1])
    return min(xs), min(ys), max(xs), max(ys)



def vector_icon_text(outline, canvases):
    lines = [
        "// Copyright 2026 boring. BSD style license.",
        "//",
        "// GENERATED by boring-core/tools/export_brand.py from the B master.",
        "// Outline from UnifrakturCook Bold (SIL Open Font License 1.1); see",
        "// boring-core/branding/source/ for the font and its licence.",
        "",
    ]
    for canvas in canvases:
        tweak = SIZE_TWEAKS[16] if canvas < 24 else None
        if tweak:
            px_, py_, pw, ph, prx = tweak["plate"]
            gs = tweak["glyph_scale"]
        else:
            px_, py_, pw, ph, prx = PLATE
            gs = 1.0
        k = canvas / 64.0
        b = outline_bounds(outline)
        cx = (b[0] + b[2]) / 2.0
        cy = (b[1] + b[3]) / 2.0

        def pt(p):
            x = (cx + (p[0] - cx) * gs) * k
            y = (cy + (p[1] - cy) * gs) * k
            return "%s, %s" % (fmt(x), fmt(y))

        lines.append("CANVAS_DIMENSIONS, %d," % canvas)
        lines.append("PATH_COLOR_ARGB, 0xFF, 0x%02X, 0x%02X, 0x%02X," % PLATE_COLOR)
        lines.append("ROUND_RECT, %s, %s, %s, %s, %s," % tuple(
            fmt(v * k) for v in (px_, py_, pw, ph, prx)))
        lines.append("NEW_PATH,")
        lines.append("PATH_COLOR_ARGB, 0xFF, 0x%02X, 0x%02X, 0x%02X," % GLYPH_COLOR)
        lines.append("FILL_RULE_NONZERO,")
        for start, segs in outline:
            lines.append("MOVE_TO, %s," % pt(start))
            for seg in segs:
                if seg[0] == "L":
                    lines.append("LINE_TO, %s," % pt(seg[1]))
                else:
                    lines.append("QUADRATIC_TO, %s, %s," % (pt(seg[1]), pt(seg[2])))
            lines.append("CLOSE,")
        lines.append("")
    return "\n".join(lines)



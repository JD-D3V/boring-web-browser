# Rasterising.


class Xform:
    """Maps the 64 box to pixels: p * scale + offset."""

    def __init__(self, scale, ox, oy):
        self.scale = scale
        self.ox = ox
        self.oy = oy

    def __call__(self, p):
        return (p[0] * self.scale + self.ox, p[1] * self.scale + self.oy)


def flatten_outline(contours, xf, glyph_scale=1.0, tol=0.05):
    b = outline_bounds(contours)
    cx = (b[0] + b[2]) / 2.0
    cy = (b[1] + b[3]) / 2.0

    def g(p):
        if glyph_scale == 1.0:
            return xf(p)
        return xf((cx + (p[0] - cx) * glyph_scale, cy + (p[1] - cy) * glyph_scale))

    polys = []
    for start, segs in contours:
        cur = g(start)
        poly = [cur]
        for seg in segs:
            if seg[0] == "L":
                cur = g(seg[1])
                poly.append(cur)
            else:
                c = g(seg[1])
                e = g(seg[2])
                dx = cur[0] - 2 * c[0] + e[0]
                dy = cur[1] - 2 * c[1] + e[1]
                dev = math.hypot(dx, dy) / 4.0
                n = max(1, int(math.ceil(math.sqrt(dev / tol))))
                for i in range(1, n + 1):
                    t = i / n
                    u = 1 - t
                    poly.append(
                        (
                            u * u * cur[0] + 2 * u * t * c[0] + t * t * e[0],
                            u * u * cur[1] + 2 * u * t * c[1] + t * t * e[1],
                        )
                    )
                cur = e
        polys.append(poly)
    return polys


def rounded_rect(x, y, w, h, r, xf, tol=0.05):
    r = min(r, w / 2.0, h / 2.0)
    rp = r * xf.scale
    if rp <= 0:
        pts = [(x, y), (x + w, y), (x + w, y + h), (x, y + h)]
        return [[xf(p) for p in pts]]
    # Segments per quarter so the chord error stays under tol pixels.
    n = max(2, int(math.ceil((math.pi / 2) / (2 * math.acos(max(-1.0, 1 - tol / rp))))))
    corners = [
        (x + w - r, y + r, -math.pi / 2),
        (x + w - r, y + h - r, 0.0),
        (x + r, y + h - r, math.pi / 2),
        (x + r, y + r, math.pi),
    ]
    pts = []
    for cx, cy, a0 in corners:
        for i in range(n + 1):
            a = a0 + (math.pi / 2) * i / n
            pts.append(xf((cx + r * math.cos(a), cy + r * math.sin(a))))
    return [pts]


def coverage(polys, width, height, ss):
    """Nonzero coverage in [0, 1]: ss sub-rows per pixel, exact spans in x."""
    edges = []
    for poly in polys:
        n = len(poly)
        for i in range(n):
            x0, y0 = poly[i]
            x1, y1 = poly[(i + 1) % n]
            if y0 == y1:
                continue
            d = 1
            if y0 > y1:
                x0, y0, x1, y1 = x1, y1, x0, y0
                d = -1
            edges.append((y0, y1, x0, (x1 - x0) / (y1 - y0), d))
    edges.sort()
    cov = [0.0] * (width * height)
    active = []
    ei = 0
    w = 1.0 / ss
    for j in range(height * ss):
        y = (j + 0.5) / ss
        while ei < len(edges) and edges[ei][0] <= y:
            active.append(edges[ei])
            ei += 1
        active = [e for e in active if e[1] > y]
        if not active:
            continue
        xs = sorted((e[2] + (y - e[0]) * e[3], e[4]) for e in active)
        row = (j // ss) * width
        wind = 0
        for k in range(len(xs) - 1):
            wind += xs[k][1]
            if wind == 0:
                continue
            a = max(0.0, xs[k][0])
            b = min(float(width), xs[k + 1][0])
            if b <= a:
                continue
            ia = int(a)
            ib = int(b)
            if ia == ib:
                cov[row + ia] += (b - a) * w
                continue
            cov[row + ia] += (ia + 1 - a) * w
            for i in range(ia + 1, ib):
                cov[row + i] += w
            if ib < width:
                cov[row + ib] += (b - ib) * w
    return [c if c < 1.0 else 1.0 for c in cov]


def supersample_for(size):
    return 16 if size > 128 else 32


class Canvas:
    """Premultiplied float RGBA."""

    def __init__(self, width, height):
        self.width = width
        self.height = height
        self.px = [(0.0, 0.0, 0.0, 0.0)] * (width * height)

    @classmethod
    def from_rgba(cls, width, height, rgba):
        c = cls(width, height)
        px = []
        for r, g, b, a in rgba:
            af = a / 255.0
            px.append((r / 255.0 * af, g / 255.0 * af, b / 255.0 * af, af))
        c.px = px
        return c

    def fill(self, cov, color):
        cr, cg, cb = (v / 255.0 for v in color)
        px = self.px
        for i, c in enumerate(cov):
            if c <= 0.0:
                continue
            r, g, b, a = px[i]
            k = 1.0 - c
            px[i] = (cr * c + r * k, cg * c + g * k, cb * c + b * k, c + a * k)

    def rgba(self):
        out = bytearray()
        for r, g, b, a in self.px:
            ai = int(round(a * 255))
            if ai <= 0:
                out += b"\0\0\0\0"
                continue
            out += bytes(
                (
                    min(255, int(round(r / a * 255))),
                    min(255, int(round(g / a * 255))),
                    min(255, int(round(b / a * 255))),
                    min(255, ai),
                )
            )
        return bytes(out)


def draw_tile(canvas, outline, scale, ox, oy, size_hint):
    """Paint plate + B with the 64 box mapped by scale/offset."""
    tweak = SIZE_TWEAKS.get(size_hint)
    if tweak:
        px_, py_, pw, ph, prx = tweak["plate"]
        gs = tweak["glyph_scale"]
        gamma = tweak["glyph_gamma"]
    else:
        px_, py_, pw, ph, prx = PLATE
        gs = 1.0
        gamma = 1.0
    xf = Xform(scale, ox, oy)
    ss = supersample_for(max(canvas.width, canvas.height))
    plate = coverage(rounded_rect(px_, py_, pw, ph, prx, xf), canvas.width, canvas.height, ss)
    canvas.fill(plate, PLATE_COLOR)
    glyph = coverage(flatten_outline(outline, xf, gs), canvas.width, canvas.height, ss)
    if gamma != 1.0:
        glyph = [c ** gamma if c > 0.0 else 0.0 for c in glyph]
    # The B only shows where the plate is (it always sits inside it).
    canvas.fill([min(a, b) for a, b in zip(glyph, plate)], GLYPH_COLOR)


def tile_image(outline, size):
    c = Canvas(size, size)
    draw_tile(c, outline, size / 64.0, 0.0, 0.0, size)
    return c


def tile_in_square(outline, width, height, left, top, side, size_hint=None):
    """B tile whose plate fills the square (left, top, side) in pixels."""
    c = Canvas(width, height)
    tweak = SIZE_TWEAKS.get(size_hint)
    px_, py_, pw, _ph, _rx = tweak["plate"] if tweak else PLATE
    scale = side / pw
    ox = left - px_ * scale
    oy = top - py_ * scale
    draw_tile(c, outline, scale, ox, oy, size_hint)
    return c



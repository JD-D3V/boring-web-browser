#!/usr/bin/env python3
"""Export the browser's B mark to every product icon slot.

The B is drawn from UnifrakturCook Bold, the blackletter face JD
approved on 2026-09-19 (artifacts/brand-review/unifrakturcook-b.png).
The font and its licence are archived under branding/source/. It is
under the SIL Open Font License 1.1, which allows redistribution, so
these outputs are cleared for distribution. The shape is approved as it
stands: do not change the glyph, the geometry or the colours without
another review.

One master drives everything:

  branding/master/b-tile.svg   plate + B, 64 box (app icon)
  branding/master/b-glyph.svg  B only, currentColor (pages)

The B is positioned exactly as design/v2/brand-preview.svg lays out its
text: 49px, text-anchor middle at x=30, baseline
y=48, on a 60x60 rx17 #176b5b plate at (2,2). The outline is written
into the SVG as a path, so nothing depends on the font at run time.

From that master this tool rasterises (pure Python: flattened quadratic
curves, nonzero fill, exact horizontal / supersampled vertical coverage)
the ICO and PNG files Chromium compiles into chrome.exe, chrome.dll and
the resource paks, and writes them under boring-core/chromium_src/ so
tools/apply.py overlays them onto the build tree (with pristine backups).
It also writes components/boring/branding/brand_mark.h for the pages.

Output is deterministic: the same inputs give byte-identical files.

Usage:
  python tools/export_brand.py                 regenerate + manifest
  python tools/export_brand.py --check         regenerate into a temp dir
                                               and verify every hash
  python tools/export_brand.py --preview DIR   also write enlarged previews
                                               on light and dark backgrounds
"""


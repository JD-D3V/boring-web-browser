# PNG and ICO.


def png_bytes(width, height, rgba):
    stride = width * 4
    raw = bytearray()
    prev = bytes(stride)
    for y in range(height):
        line = rgba[y * stride : (y + 1) * stride]
        sub = bytes((line[i] - (line[i - 4] if i >= 4 else 0)) & 255 for i in range(stride))
        up = bytes((line[i] - prev[i]) & 255 for i in range(stride))
        best = min(
            ((0, line), (1, sub), (2, up)),
            key=lambda fl: sum(v if v < 128 else 256 - v for v in fl[1]),
        )
        raw.append(best[0])
        raw += best[1]
        prev = line

    def chunk(tag, body):
        return (
            struct.pack(">I", len(body))
            + tag
            + body
            + struct.pack(">I", zlib.crc32(tag + body) & 0xFFFFFFFF)
        )

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )


def png_decode(data):
    p = 8
    idat = b""
    pal = trns = None
    while p < len(data):
        length = struct.unpack(">I", data[p : p + 4])[0]
        tag = data[p + 4 : p + 8]
        body = data[p + 8 : p + 8 + length]
        p += 12 + length
        if tag == b"IHDR":
            w, h, depth, ct, _c, _f, interlace = struct.unpack(">IIBBBBB", body)
        elif tag == b"IDAT":
            idat += body
        elif tag == b"PLTE":
            pal = body
        elif tag == b"tRNS":
            trns = body
    if depth != 8 or interlace:
        raise SystemExit("only 8-bit non-interlaced PNG sources are supported")
    bpp = {6: 4, 2: 3, 3: 1, 0: 1, 4: 2}[ct]
    raw = zlib.decompress(idat)
    stride = w * bpp
    prev = bytearray(stride)
    out = []
    i = 0
    for _y in range(h):
        ft = raw[i]
        line = bytearray(raw[i + 1 : i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if ft == 1:
                line[x] = (line[x] + a) & 255
            elif ft == 2:
                line[x] = (line[x] + b) & 255
            elif ft == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif ft == 4:
                pp = a + b - c
                pa, pb, pc = abs(pp - a), abs(pp - b), abs(pp - c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[x] = (line[x] + pr) & 255
        for x in range(w):
            if ct == 6:
                out.append(tuple(line[4 * x : 4 * x + 4]))
            elif ct == 2:
                out.append(tuple(line[3 * x : 3 * x + 3]) + (255,))
            elif ct == 3:
                k = line[x]
                alpha = trns[k] if trns and k < len(trns) else 255
                out.append(tuple(pal[3 * k : 3 * k + 3]) + (alpha,))
            elif ct == 0:
                out.append((line[x], line[x], line[x], 255))
            else:
                out.append((line[2 * x], line[2 * x], line[2 * x], line[2 * x + 1]))
        prev = line
    return w, h, out


def bmp32_frame(width, height, rgba):
    """BITMAPINFOHEADER + bottom-up BGRA + AND mask, as Windows icons store it."""
    mask_stride = ((width + 31) // 32) * 4
    xor = bytearray()
    mask = bytearray()
    for y in range(height - 1, -1, -1):
        row = rgba[y * width * 4 : (y + 1) * width * 4]
        bits = bytearray(mask_stride)
        for x in range(width):
            r, g, b, a = row[4 * x : 4 * x + 4]
            xor += bytes((b, g, r, a))
            if a == 0:
                bits[x // 8] |= 0x80 >> (x % 8)
        mask += bits
    header = struct.pack(
        "<IiiHHIIiiII", 40, width, height * 2, 1, 32, 0, len(xor) + len(mask), 0, 0, 0, 0
    )
    return header + bytes(xor) + bytes(mask)


def ico_bytes(frames):
    """frames: list of (size, rgba). 256 is stored as PNG, the rest BMP32."""
    frames = sorted(frames, key=lambda f: f[0])
    blobs = []
    for size, rgba in frames:
        if size >= 256:
            blobs.append((size, png_bytes(size, size, rgba)))
        else:
            blobs.append((size, bmp32_frame(size, size, rgba)))
    out = bytearray(struct.pack("<HHH", 0, 1, len(blobs)))
    offset = 6 + 16 * len(blobs)
    for size, blob in blobs:
        dim = 0 if size >= 256 else size
        out += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(blob), offset)
        offset += len(blob)
    for _size, blob in blobs:
        out += blob
    return bytes(out)


def ico_decode(data):
    """32-bit frames of an ICO as {size: rgba tuples}. Palette frames are skipped."""
    count = struct.unpack("<H", data[4:6])[0]
    frames = {}
    for i in range(count):
        w, h, _c, _r, _p, _b, size, off = struct.unpack(
            "<BBBBHHII", data[6 + 16 * i : 22 + 16 * i]
        )
        w = w or 256
        h = h or 256
        blob = data[off : off + size]
        if blob[:4] == b"\x89PNG":
            pw, ph, px = png_decode(blob)
            frames[pw] = px
            continue
        bw, bh2, _planes, bpp = struct.unpack("<IiHH", blob[4:16])
        if bpp != 32:
            continue
        hdr = struct.unpack("<I", blob[:4])[0]
        pix = blob[hdr : hdr + bw * bw * 4]
        rows = []
        for y in range(bw):
            r = pix[y * bw * 4 : (y + 1) * bw * 4]
            rows.append([(r[4 * x + 2], r[4 * x + 1], r[4 * x], r[4 * x + 3]) for x in range(bw)])
        rows.reverse()
        frames[bw] = [p for row in rows for p in row]
    return frames



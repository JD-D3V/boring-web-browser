# Document / PDF association icons: keep Chromium's page, swap the emblem.


def is_emblem(p):
    r, g, b, a = p
    return a > 60 and b > r + 30 and b > g + 10


def is_label(p):
    r, g, b, a = p
    return a > 200 and max(r, g, b) < 110 and abs(r - g) < 24 and abs(g - b) < 24


def page_color(px, size, y, x_from, step):
    x = x_from
    while 0 <= x < size:
        r, g, b, a = px[y * size + x]
        if a == 255 and min(r, g, b) > 180 and not is_emblem(px[y * size + x]):
            return (r, g, b, a)
        x += step
    return None


def swap_emblem(outline, size, px, keep_label):
    xs = []
    ys = []
    for i, p in enumerate(px):
        if is_emblem(p):
            xs.append(i % size)
            ys.append(i // size)
    if not xs:
        raise SystemExit("no Chromium emblem found in %d px document frame" % size)
    top, bottom, left = min(ys), max(ys) + 1, min(xs)
    radius = (bottom - top) / 2.0
    cy = top + radius
    cx = left + radius

    # Chromium only draws the "PDF" label on its large frames; the small
    # PDF frames are identical to the document ones.
    label = None
    if keep_label and size >= 64:
        lx = [i % size for i, p in enumerate(px) if is_label(p)]
        ly = [i // size for i, p in enumerate(px) if is_label(p)]
        if lx:
            box = (min(lx), min(ly), max(lx) + 1, max(ly) + 1)
            if box[2] - box[0] >= size // 3 and box[3] - box[1] >= size // 8:
                label = box

    # Paint the page back over the emblem, row by row, from the nearest
    # clean page pixels on either side.
    out = list(px)
    reach = radius + 1.0
    for y in range(max(0, int(cy - reach)), min(size, int(math.ceil(cy + reach)))):
        yc = y + 0.5
        dy = yc - cy
        if abs(dy) > reach:
            continue
        half = math.sqrt(max(0.0, reach * reach - dy * dy))
        xa = max(0, int(math.floor(cx - half)))
        xb = min(size - 1, int(math.ceil(cx + half)))
        lc = page_color(px, size, y, xa - 1, -1)
        rc = page_color(px, size, y, xb + 1, 1)
        if lc is None and rc is None:
            continue
        lc = lc or rc
        rc = rc or lc
        for x in range(xa, xb + 1):
            dx = x + 0.5 - cx
            if dx * dx + dy * dy > reach * reach:
                continue
            t = (x - xa + 0.5) / (xb - xa + 1)
            out[y * size + x] = tuple(
                int(round(lc[k] * (1 - t) + rc[k] * t)) for k in range(4)
            )

    canvas = Canvas.from_rgba(size, size, out)
    if size >= 64:
        # A rounded square reads larger than a circle of the same width.
        side = 2 * radius * 0.9
        left = cx - side / 2
        top = cy - side / 2
    else:
        # Small frames: fill the emblem's footprint on whole pixels so the
        # plate edges stay crisp.
        side = float(round(2 * radius))
        left = float(round(cx - side / 2))
        top = float(round(cy - side / 2))
    hint = 16 if side < 28 else None
    tile = tile_in_square(outline, size, size, left, top, side, hint)
    # Composite the tile over the page (source-over, premultiplied).
    merged = []
    for (r, g, b, a), (tr, tg, tb, ta) in zip(canvas.px, tile.px):
        k = 1.0 - ta
        merged.append((tr + r * k, tg + g * k, tb + b * k, ta + a * k))
    canvas.px = merged
    result = bytearray(canvas.rgba())
    if label:
        x0, y0, x1, y1 = label
        for y in range(y0, y1):
            for x in range(x0, x1):
                r, g, b, a = px[y * size + x]
                # Label body and its white text are neutral; anything
                # tinted blue is the old emblem showing at the edge.
                if a < 200 or abs(r - g) >= 24 or abs(g - b) >= 24:
                    continue
                i = (y * size + x) * 4
                result[i : i + 4] = bytes((r, g, b, a))
    return bytes(result)


def doc_ico(outline, source_bytes, keep_label):
    frames = ico_decode(source_bytes)
    out = []
    for size in sorted(frames):
        out.append((size, swap_emblem(outline, size, frames[size], keep_label)))
    return ico_bytes(out), sorted(frames)



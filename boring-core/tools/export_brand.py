def check(font_path):
    tmp = tempfile.mkdtemp(prefix="boring-brand-")
    ok = True
    try:
        # Sources are read from CORE; outputs go to the temp root.
        fresh = generate(tmp, font_path)
        with open(os.path.join(CORE, MANIFEST), "rb") as f:
            recorded = json.loads(f.read().decode("utf-8"))
        want = {r["path"]: r["sha256"] for r in recorded["outputs"]}
        got = {r["path"]: r["sha256"] for r in fresh["outputs"]}
        for inp_new, inp_old in zip(fresh["inputs"], recorded["inputs"]):
            if inp_new["sha256"] != inp_old["sha256"]:
                print("INPUT CHANGED", inp_old["path"])
                ok = False
        for path in sorted(set(want) | set(got)):
            if want.get(path) != got.get(path):
                print("REGENERATED DIFFERS", path)
                ok = False
                continue
            try:
                with open(os.path.join(CORE, path.replace("/", os.sep)), "rb") as f:
                    have = sha256(normalized(path, f.read()))
            except OSError:
                print("MISSING", path)
                ok = False
                continue
            if have != got[path]:
                print("CHECKED-IN FILE DIFFERS", path)
                ok = False
        with open(os.path.join(tmp, MANIFEST), "rb") as f:
            new_manifest = f.read()
        with open(os.path.join(CORE, MANIFEST), "rb") as f:
            if normalized(".json", f.read()) != new_manifest:
                print("MANIFEST DIFFERS")
                ok = False
        # The header must carry the masters byte for byte.
        with open(os.path.join(tmp, HEADER), "rb") as f:
            header = f.read().decode("utf-8")
        for rel in (TILE_SVG, GLYPH_SVG):
            with open(os.path.join(tmp, rel), "rb") as f:
                if 'R"SVG(' + f.read().decode("utf-8") + ')SVG"' not in header:
                    print("HEADER DOES NOT EMBED", rel)
                    ok = False
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("check: %s (%d outputs)" % ("OK" if ok else "FAILED", len(got)))
    return ok


def preview(dest):
    """Enlarged previews of every PNG/ICO frame on light and dark grounds."""
    manifest_path = os.path.join(CORE, MANIFEST)
    with open(manifest_path, encoding="utf-8") as f:
        manifest = json.load(f)
    os.makedirs(dest, exist_ok=True)
    for rec in manifest["outputs"]:
        path = os.path.join(CORE, rec["path"].replace("/", os.sep))
        with open(path, "rb") as f:
            data = f.read()
        if path.endswith(".png"):
            w, h, px = png_decode(data)
            images = [("", w, h, px)]
        elif path.endswith(".ico"):
            images = [("_%d" % s, s, s, px) for s, px in sorted(ico_decode(data).items())]
        else:
            continue
        base = rec["path"].replace("chromium_src/", "").replace("/", "_").replace(".", "_")
        for suffix, w, h, px in images:
            zoom = max(1, min(8, 256 // max(w, h)))
            for ground_name, ground in (("light", (255, 255, 255)), ("dark", (32, 33, 36))):
                out = bytearray()
                for y in range(h * zoom):
                    for x in range(w * zoom):
                        r, g, b, a = px[(y // zoom) * w + x // zoom]
                        k = a / 255.0
                        out += bytes(
                            int(round(c * k + gc * (1 - k))) for c, gc in zip((r, g, b), ground)
                        ) + b"\xff"
                name = "%s%s_%s.png" % (base, suffix, ground_name)
                with open(os.path.join(dest, name), "wb") as f:
                    f.write(png_bytes(w * zoom, h * zoom, bytes(out)))
    print("previews in", dest)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--preview", metavar="DIR")
    args = ap.parse_args()
    if args.check:
        sys.exit(0 if check(args.font) else 1)
    manifest = generate(CORE, args.font)
    print("wrote %d outputs (approved B, UnifrakturCook Bold, OFL 1.1)"
          % len(manifest["outputs"]))
    if args.preview:
        preview(args.preview)


if __name__ == "__main__":
    main()
